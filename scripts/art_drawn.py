# Каждая иконка — сетка символов; '.' — прозрачно. Палитра общая плюс своя у иконки.
from PIL import Image

BASE = {
    ".": (0, 0, 0, 0),
    "K": (38, 34, 40), "k": (62, 58, 66),                                # контур
    "W": (245, 248, 252), "1": (208, 214, 224), "2": (140, 148, 162), "3": (92, 98, 108),  # металл
    "r": (206, 48, 58), "R": (160, 20, 30), "q": (100, 12, 18), "p": (230, 90, 100),   # кровь / красный
}


def draw(rows, pal=None):
    p = dict(BASE)
    if pal:
        p.update(pal)
    assert len(rows) == 16, len(rows)
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        row = row.ljust(16, ".")
        assert len(row) == 16, (y, row)
        for x, ch in enumerate(row):
            c = p[ch]
            im.putpixel((x, y), c if len(c) == 4 else c + (255,))
    return im


